import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { maskContent, unmaskContent } from './transformer.js';
import { scanForSecrets } from './detector.js';
import { saveSession, loadSession, inspectSession, DEFAULT_SESSION_FILENAME } from './session.js';

function readStdin() {
  return new Promise((resolve, reject) => {
    let data = '';
    process.stdin.setEncoding('utf8');
    process.stdin.on('data', chunk => {
      data += chunk;
    });
    process.stdin.on('end', () => {
      resolve(data);
    });
    process.stdin.on('error', err => {
      reject(err);
    });
  });
}

function parseArgs(args) {
  const flags = {};
  const positional = [];

  for (let i = 0; i < args.length; i++) {
    const arg = args[i];
    if (arg.startsWith('--')) {
      let key = arg.slice(2);
      if (key === 'in-place') key = 'inPlace';
      if (key.includes('=')) {
        const [k, v] = key.split('=');
        flags[k === 'in-place' ? 'inPlace' : k] = v;
      } else if (i + 1 < args.length && !args[i + 1].startsWith('-')) {
        flags[key] = args[++i];
      } else {
        flags[key] = true;
      }
    } else if (arg.startsWith('-') && arg.length === 2) {
      const char = arg.charAt(1);
      const map = {
        s: 'session',
        o: 'out',
        p: 'passphrase',
        i: 'inPlace',
        h: 'help',
        v: 'version',
      };
      const key = map[char] || char;
      if (key !== 'inPlace' && key !== 'help' && key !== 'version' && i + 1 < args.length && !args[i + 1].startsWith('-')) {
        flags[key] = args[++i];
      } else {
        flags[key] = true;
      }
    } else {
      positional.push(arg);
    }
  }

  return { flags, positional };
}

function printHelp() {
  const helpText = `
codemask: Zero-dependency reversible secret masking for LLM code workflows

USAGE:
  codemask <command> [file] [options]

COMMANDS:
  mask [file]       Scan and replace secrets with syntax-preserving placeholders
  unmask [file]     Restore original secrets from session mapping
  scan [file]       Audit file or stdin for unmasked secrets (exits 1 if found)
  inspect           View tokens and masked secrets in current session
  clean             Remove current session file

OPTIONS:
  -i, --in-place    Modify file directly in-place (requires file argument)
  -s, --session     Session map file path (default: .codemask-session.json)
  -o, --out         Target file to write transformed output (default: stdout)
  -p, --passphrase  Passphrase to encrypt/decrypt session mapping file
      --reveal      Reveal unmasked secrets during inspect command
      --strict      Fail with exit code 1 if unmask leaves lingering placeholders
      --stats       Print detection counts to stderr
  -h, --help        Show this help message
  -v, --version     Show version number

EXAMPLES:
  # Mask sensitive code and pipe to LLM prompt
  cat src/config.ts | codemask mask > prompt.txt

  # Unmask code generated by LLM and restore original secrets
  cat response.ts | codemask unmask > src/config.ts

  # Mask a specific file in place
  codemask mask src/api.py -i

  # Audit code for secrets before commit (CI / pre-commit)
  codemask scan src/config.ts

  # Inspect masked session tokens
  codemask inspect
`;
  console.log(helpText.trim());
}

export async function runCLI(argv = process.argv.slice(2)) {
  const { flags, positional } = parseArgs(argv);
  const command = positional[0] || (flags.help ? 'help' : flags.version ? 'version' : '');

  if (flags.version || command === 'version') {
    console.log('codemask v1.1.0');
    return;
  }

  if (flags.help || !command || command === 'help') {
    printHelp();
    return;
  }

  const sessionFile = flags.session || DEFAULT_SESSION_FILENAME;
  const passphrase = flags.passphrase || process.env.CODEMASK_PASSPHRASE || null;
  const filePath = positional[1];

  async function getContent() {
    if (filePath) {
      const fullPath = path.resolve(filePath);
      if (!fs.existsSync(fullPath)) {
        throw new Error(`File not found: ${fullPath}`);
      }
      return fs.readFileSync(fullPath, 'utf8');
    }
    if (!process.stdin.isTTY) {
      return await readStdin();
    }
    throw new Error('No input provided. Provide a file path or pipe content through stdin.');
  }

  function outputResult(content) {
    if (flags.inPlace) {
      if (!filePath) {
        throw new Error('--in-place option requires a file path argument.');
      }
      fs.writeFileSync(path.resolve(filePath), content, 'utf8');
    } else if (flags.out) {
      fs.writeFileSync(path.resolve(flags.out), content, 'utf8');
    } else {
      process.stdout.write(content);
    }
  }

  try {
    switch (command) {
      case 'mask': {
        const input = await getContent();
        let existingMapping = {};
        if (fs.existsSync(sessionFile)) {
          try {
            existingMapping = loadSession(sessionFile, passphrase);
          } catch {
            existingMapping = {};
          }
        }

        const { maskedContent, mapping, findingsCount, uniqueCount } = maskContent(input, existingMapping);
        saveSession(sessionFile, mapping, passphrase);

        outputResult(maskedContent);

        if (flags.stats || (!flags.out && !flags.inPlace && process.stderr.isTTY)) {
          process.stderr.write(`\n[codemask] Masked ${findingsCount} secrets (${uniqueCount} unique) into ${sessionFile}\n`);
        }
        break;
      }

      case 'unmask': {
        const input = await getContent();
        const mapping = loadSession(sessionFile, passphrase);
        const { unmaskedContent, restoredCount, unmatchedPlaceholders } = unmaskContent(input, mapping);

        outputResult(unmaskedContent);

        if (unmatchedPlaceholders && unmatchedPlaceholders.length > 0) {
          process.stderr.write(`\n[codemask warning] ${unmatchedPlaceholders.length} unresolved placeholder(s) detected: ${unmatchedPlaceholders.join(', ')}\n`);
          if (flags.strict) {
            process.exitCode = 1;
          }
        }

        if (flags.stats || (!flags.out && !flags.inPlace && process.stderr.isTTY)) {
          process.stderr.write(`\n[codemask] Restored ${restoredCount} secret occurrences from ${sessionFile}\n`);
        }
        break;
      }

      case 'scan':
      case 'check': {
        const input = await getContent();
        const findings = scanForSecrets(input);

        if (findings.length === 0) {
          console.log(`[codemask scan] Clean: No unmasked secrets detected.`);
          return;
        }

        console.error(`\n[codemask scan] Alert: Found ${findings.length} unmasked secret(s):\n`);
        console.error(`| # | Rule Name | Category | Preview |`);
        console.error(`| :--- | :--- | :--- | :--- |`);

        findings.forEach((f, idx) => {
          let preview;
          if (f.rawSecret.length <= 8) {
            preview = '***';
          } else {
            const head = f.rawSecret.substring(0, 3);
            const tail = f.rawSecret.substring(f.rawSecret.length - 3);
            preview = `${head}...${tail} (${f.rawSecret.length} chars)`;
          }
          console.error(`| ${idx + 1} | ${f.ruleName} | ${f.category} | ${preview} |`);
        });

        console.error(`\nRun 'codemask mask' to sanitize sensitive values.\n`);
        process.exitCode = 1;
        break;
      }

      case 'inspect': {
        const items = inspectSession(sessionFile, passphrase, Boolean(flags.reveal));
        if (items.length === 0) {
          console.log(`[codemask] Session ${sessionFile} contains no masked items.`);
          return;
        }

        console.log(`\nSession: ${sessionFile} (${items.length} unique tokens)\n`);
        console.log(`| Placeholder Token | Original Value | Length |`);
        console.log(`| :--- | :--- | :--- |`);
        for (const item of items) {
          console.log(`| ${item.placeholder} | ${item.preview} | ${item.originalLength} |`);
        }
        console.log('');
        break;
      }

      case 'clean': {
        const resolved = path.resolve(sessionFile);
        if (fs.existsSync(resolved)) {
          fs.unlinkSync(resolved);
          console.log(`[codemask] Removed session file: ${resolved}`);
        } else {
          console.log(`[codemask] Session file does not exist: ${resolved}`);
        }
        break;
      }

      default:
        console.error(`Unknown command: ${command}`);
        printHelp();
        process.exitCode = 1;
    }
  } catch (err) {
    console.error(`[codemask error] ${err.message}`);
    process.exitCode = 1;
  }
}
